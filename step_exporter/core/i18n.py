def _get_language():
    try:
        lang = bpy.context.preferences.view.language
        if lang and ('zh' in str(lang).lower() or 'chinese' in str(lang).lower()):
            return 'zh_CN'
    except: pass
    try:
        locale = bpy.app.translations.locale
        if locale and 'zh' in str(locale).lower():
            return 'zh_CN'
    except: pass
    return 'en'

def _t(key, **kwargs):
    lang = _get_language()
    if lang == 'en': result = key
    else:
        entry = _STRINGS.get(key)
        result = entry.get(lang, key) if entry else key
    if kwargs:
        try: result = result.format(**kwargs)
        except: pass
    return result

def _build_translations():
    zh_entries = {}
    for en_str, loc in _STRINGS.items():
        zh = loc.get('zh_CN', en_str)
        zh_entries[('*', en_str)] = zh
        zh_entries[('Operator', en_str)] = zh
    return {'zh_CN': zh_entries, 'zh': zh_entries}

def register_translations():
    try:
        trans = _build_translations()
        bpy.app.translations.register("step_exporter", trans)
    except: pass

def unregister_translations():
    try:
        bpy.app.translations.unregister("step_exporter")
    except: pass
